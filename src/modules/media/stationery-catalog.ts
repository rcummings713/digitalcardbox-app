export const stationeryLayouts = [
  "portrait",
  "editorial",
  "arch",
  "postcard",
] as const;
export type StationeryLayout = (typeof stationeryLayouts)[number];
const tones = {
  blush: ["#f9eeea", "#573d39", "#ac756a"],
  ivory: ["#fff9ed", "#51422f", "#ac884e"],
  sage: ["#edf0e7", "#354b3d", "#6e8769"],
  midnight: ["#263b50", "#fff5de", "#d9bc79"],
  lilac: ["#f0e7f3", "#553d5d", "#a57ba9"],
  ocean: ["#e7eef1", "#354e60", "#738c9d"],
} as const;
export const stationeryTemplates = stationeryFamilies.flatMap((family) =>
  stationeryLayouts.map((layout) => ({
    id: `atelier-${family.id}-${layout}` as const,
    name: `${family.name} · ${layout === "portrait" ? "Classic" : layout === "editorial" ? "Editorial" : layout === "arch" ? "Arch" : "Postcard"}`,
    description: `Original ${family.name.toLowerCase()} stationery with a ${layout} composition and editable text.`,
    motif: `atelier-${family.motif}`,
    family: family.id,
    layout,
    category: family.category,
    palette: family.palette,
    paper: tones[family.palette][0],
    ink: tones[family.palette][1],
    accent: tones[family.palette][2],
  })),
);
